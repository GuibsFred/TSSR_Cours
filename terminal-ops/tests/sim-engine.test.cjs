const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx={window:{}};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../sim-engine.js'),'utf8'),ctx);
const e=ctx.window.TerminalOpsSim;
const run=x=>e.execute(x);
e.reset('cmd-dns');
assert.match(run('ipconfig /displaydns').v,/192\.168\.10\.99/);
assert.match(run('nslookup intranet.agence.local').v,/192\.168\.10\.25/);
assert.match(run('ping intranet.agence.local').v,/perte 100/);
run('ipconfig /all');run('ipconfig /flushdns');
assert.match(run('ping intranet.agence.local').v,/perte 0/);
assert.equal(JSON.stringify(e.status().steps),'[true,true,true]');
e.reset('cmd-route');run('ipconfig /all');run('route print');run('route add 0.0.0.0 mask 0.0.0.0 192.168.10.1');run('ping 192.168.10.1');
assert.equal(JSON.stringify(e.status().steps),'[true,true,true]');
e.reset('cmd-dns');run('sc stop Dnscache');
assert.equal(e.status().services.Dnscache,'STOPPED');
run('sc start Dnscache');assert.equal(e.status().services.Dnscache,'RUNNING');
e.reset('cmd-dns');run('ipconfig /release');
assert.match(run('ipconfig /all').v,/0\.0\.0\.0/);
run('ipconfig /renew');assert.match(run('ipconfig /all').v,/192\.168\.10\.42/);
console.log('OK — DNS, routage, services et DHCP simulés');
